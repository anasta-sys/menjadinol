drop policy if exists "staff delete content" on public.content_entries;
create policy "staff delete content" on public.content_entries for delete to authenticated using((select auth.jwt()->>'aal')='aal2' and public.is_active_staff() and (author_id=auth.uid() or public.is_admin()));

