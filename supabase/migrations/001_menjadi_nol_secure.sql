-- Automatically create reader profile after Auth sign-up; staff invitations are ignored.
create or replace function public.handle_new_reader() returns trigger
language plpgsql security definer set search_path=public as $$
begin
  if coalesce(new.raw_user_meta_data->>'account_type','')='reader' then
    insert into public.reader_users(user_id,email,name)
    values(new.id,coalesce(new.email,''),new.raw_user_meta_data->>'name')
    on conflict(user_id) do update set email=excluded.email,name=coalesce(excluded.name,public.reader_users.name);
  end if;
  return new;
end;$$;
drop trigger if exists on_auth_user_created_reader on auth.users;
create trigger on_auth_user_created_reader after insert or update of raw_user_meta_data,email on auth.users for each row execute procedure public.handle_new_reader();
