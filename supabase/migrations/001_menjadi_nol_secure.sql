-- Helper functions used by RLS.
create or replace function public.is_active_staff() returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.admin_users a where a.user_id=auth.uid() and a.is_active)
$$;
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.admin_users a where a.user_id=auth.uid() and a.is_active and a.role in('admin','superadmin'))
$$;
create or replace function public.is_superadmin() returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.admin_users a where a.user_id=auth.uid() and a.is_active and a.role='superadmin')
$$;

-- Staff can read their own access row; superadmin can manage all rows.
drop policy if exists "staff read self" on public.admin_users;
create policy "staff read self" on public.admin_users for select to authenticated using(user_id=auth.uid() or public.is_superadmin());
drop policy if exists "superadmin manage staff" on public.admin_users;
create policy "superadmin manage staff" on public.admin_users for all to authenticated using(public.is_superadmin()) with check(public.is_superadmin());

-- Published content/folders may be read by app server. Staff AAL2 can manage.
drop policy if exists "staff select content" on public.content_entries;
create policy "staff select content" on public.content_entries for select to authenticated using((select auth.jwt()->>'aal')='aal2' and public.is_active_staff());
drop policy if exists "staff insert content" on public.content_entries;
create policy "staff insert content" on public.content_entries for insert to authenticated with check(author_id=auth.uid() and (select auth.jwt()->>'aal')='aal2' and public.is_active_staff());
drop policy if exists "staff update content" on public.content_entries;
